pub fn t(lang: &Lang) -> &'static Texts {
    match lang {
        Lang::Pt => PT,
        Lang::En => EN,
    }
}

pub fn month_name(lang: Lang, month: u32) -> &'static str {
    const PT_MONTHS: [&str; 12] = [
        "Janeiro",
        "Fevereiro",
        "Março",
        "Abril",
        "Maio",
        "Junho",
        "Julho",
        "Agosto",
        "Setembro",
        "Outubro",
        "Novembro",
        "Dezembro",
    ];
    const EN_MONTHS: [&str; 12] = [
        "January",
        "February",
        "March",
        "April",
        "May",
        "June",
        "July",
        "August",
        "September",
        "October",
        "November",
        "December",
    ];
    match lang {
        Lang::Pt => PT_MONTHS[(month - 1) as usize],
        Lang::En => EN_MONTHS[(month - 1) as usize],
    }
}
